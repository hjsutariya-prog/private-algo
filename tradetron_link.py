"""Windows-protected configuration for an undeployed Tradetron paper executor.

The linked credential is never exposed.  The executable signal contract is
defined separately, but dispatch remains locked until the private template and
paper deployment have each been verified.
"""
import json
import os
from pathlib import Path
import re
import tempfile
from urllib.parse import parse_qs, urlsplit

from credential_store import CredentialStoreError, WindowsCredentialManager, WindowsProtection
from tradetron_protocol import template_contract


TOKEN_PATTERN = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\Z", re.I)
STRATEGY_PATTERN = re.compile(r"[0-9]{5,16}\Z")
SAFE_SIGNAL_PATTERN = re.compile(r"[A-Za-z][A-Za-z0-9_]{0,63}\Z")


def parse_api_link(value):
    """Validate the generated API-control link without ever returning it."""
    if not isinstance(value, str) or len(value) > 1024:
        raise ValueError("Paste the API link generated by Tradetron.")
    parsed = urlsplit(value.strip())
    if (parsed.scheme, parsed.netloc, parsed.path) != ("https", "api.tradetron.tech", "/api"):
        raise ValueError("Use the API link generated for this Tradetron strategy.")
    values = parse_qs(parsed.query, strict_parsing=True)
    if set(values) != {"auth-token", "key", "value"} or any(len(item) != 1 for item in values.values()):
        raise ValueError("The Tradetron API link is incomplete.")
    token, key, signal_value = values["auth-token"][0], values["key"][0], values["value"][0]
    if not TOKEN_PATTERN.fullmatch(token) or not SAFE_SIGNAL_PATTERN.fullmatch(key) or len(signal_value) > 256:
        raise ValueError("The Tradetron API link is invalid.")
    return {"auth_token": token, "signal_key": key, "signal_value": signal_value}


def valid_details(details):
    return (isinstance(details, dict)
            and set(details) == {"strategy_id", "auth_token", "signal_key", "signal_value"}
            and isinstance(details["strategy_id"], str) and STRATEGY_PATTERN.fullmatch(details["strategy_id"])
            and isinstance(details["auth_token"], str) and TOKEN_PATTERN.fullmatch(details["auth_token"])
            and isinstance(details["signal_key"], str) and SAFE_SIGNAL_PATTERN.fullmatch(details["signal_key"])
            and isinstance(details["signal_value"], str) and 0 < len(details["signal_value"]) <= 256)


class TradetronLinkStore:
    """DPAPI storage separate from Kite credentials and paper records."""
    HEADER = b"PrivateAlgoDesk-Tradetron-DPAPI-v1\n"

    def __init__(self, path, protection=None, credential_manager=None):
        self.path = Path(path)
        self.protection = protection or WindowsProtection()
        self.credential_manager = credential_manager if credential_manager is not None else (
            WindowsCredentialManager(self.path, "Tradetron") if isinstance(self.protection, WindowsProtection) else None)

    @property
    def available(self):
        return self.protection.available or bool(self.credential_manager and self.credential_manager.available)

    @staticmethod
    def _decode(payload):
        details = json.loads(payload)
        if not valid_details(details):
            raise ValueError()
        return details

    def _manager_load(self):
        if not self.credential_manager:
            return None
        payload = self.credential_manager.load()
        return None if payload is None else self._decode(payload)

    def load(self):
        try:
            with self.path.open("rb") as saved:
                encrypted = saved.read(16385)
            if len(encrypted) > 16384 or not encrypted.startswith(self.HEADER):
                raise ValueError()
            return self._decode(self.protection.unprotect(encrypted[len(self.HEADER):]))
        except FileNotFoundError:
            try:
                return self._manager_load()
            except (OSError, ValueError):
                raise CredentialStoreError("Saved Tradetron link could not be unlocked. Link it again or choose Forget executor link.") from None
        except (OSError, ValueError):
            try:
                fallback = self._manager_load()
                if fallback is not None:
                    return fallback
            except (OSError, ValueError):
                pass
            raise CredentialStoreError("Saved Tradetron link could not be unlocked. Link it again or choose Forget executor link.") from None

    def save(self, details):
        if not valid_details(details):
            raise CredentialStoreError("The Tradetron link could not be saved. Check the strategy ID and API link.")
        temporary = None
        try:
            encrypted = self.HEADER + self.protection.protect(json.dumps(details).encode("utf-8"))
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=self.path.parent, prefix=".tradetron-", delete=False) as saved:
                temporary = Path(saved.name)
                saved.write(encrypted)
                saved.flush()
                os.fsync(saved.fileno())
            os.replace(temporary, self.path)
            temporary = None
        except (OSError, ValueError):
            if self.credential_manager:
                try:
                    self.credential_manager.save(json.dumps(details, separators=(",", ":")).encode("utf-8"))
                    try:
                        self.path.unlink(missing_ok=True)
                    except OSError:
                        pass
                    return
                except (OSError, ValueError):
                    pass
            raise CredentialStoreError("Tradetron link was not saved. Windows protection or file access failed.") from None
        finally:
            if temporary is not None:
                try:
                    temporary.unlink(missing_ok=True)
                except OSError:
                    pass

    def forget(self):
        manager_error = None
        if self.credential_manager:
            try:
                self.credential_manager.forget()
            except CredentialStoreError as exc:
                manager_error = exc
        try:
            self.path.unlink(missing_ok=True)
        except OSError:
            raise CredentialStoreError("Saved Tradetron link could not be removed. It has not been forgotten; check file access and try again.") from None
        if manager_error:
            raise manager_error


class TradetronLinkState:
    """Paper-executor link with a visible, paper-only portal signal contract."""
    def __init__(self, store):
        self.store = store
        self.details = None
        self.saved = False
        self.warning = None
        self.delivery = "disabled"
        self.message = "Link a paper-only Tradetron executor when you are ready."
        try:
            self.details = store.load()
            self.saved = bool(self.details)
            if self.details:
                self.delivery = "unverified"
                self.message = "Paper executor linked. It has not yet passed an exact paper-delivery check."
        except CredentialStoreError as exc:
            self.warning = str(exc)
            self.message = str(exc)

    def status(self):
        return {"linked": bool(self.details),
                "strategy_id": self.details["strategy_id"] if self.details else None,
                "credentials_saved": self.saved,
                "credential_storage_available": self.store.available,
                "credential_storage_warning": self.warning,
                "delivery": self.delivery,
                "mode": "paper_only",
                "signal_contract": template_contract(),
                "message": self.message}

    def configure(self, payload):
        if set(payload) != {"strategy_id", "api_link", "remember"}:
            raise ValueError("Enter the Tradetron strategy ID and its generated API link.")
        strategy_id, remember = payload["strategy_id"], payload["remember"]
        if not isinstance(strategy_id, str) or not STRATEGY_PATTERN.fullmatch(strategy_id):
            raise ValueError("The Tradetron strategy ID is invalid.")
        if remember is not True:
            raise ValueError("Keep the paper executor link protected on this Windows account.")
        if not self.store.available:
            raise CredentialStoreError("Saving the Tradetron link requires Windows account protection.")
        details = {"strategy_id": strategy_id, **parse_api_link(payload["api_link"])}
        self.store.save(details)
        self.details, self.saved, self.warning = details, True, None
        self.delivery = "unverified"
        self.message = "Paper executor linked. It has not yet passed an exact paper-delivery check."
        return self.status()

    def mark_delivery_verified(self):
        """Record that Tradetron accepted the current paper-delivery check."""
        if not self.details:
            return
        self.delivery = "verified"
        self.message = "Tradetron accepted the exact CE and PE paper-delivery payloads. No broker order was sent by this app."

    def mark_delivery_rejected(self):
        """Surface a remote rejection without retaining the sensitive response."""
        if not self.details:
            return
        self.delivery = "needs_relink"
        self.message = ("Tradetron rejected the saved API link. Generate a new API link for this exact "
                        "strategy, then replace the protected link here.")

    def clear(self):
        self.store.forget()
        self.details, self.saved, self.warning = None, False, None
        self.delivery = "disabled"
        self.message = "Paper executor link removed. No Tradetron signals can be sent."
        return self.status()
